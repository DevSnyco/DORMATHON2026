// server/lib/aiFiles.js
// Converts provider governance rules into harness-specific AI guideline files:
//   - AGENTS.md        (agent behaviour / operating rules)
//   - COMMANDCODE.md   (command & tool usage policy)
//   - IRYS.md          (governance manifest: scope, compliance, servers, deploy)
// Two authoring modes:
//   - describe : admin explains in plain language + toggles + checklists -> structured files
//   - manual   : admin writes the sections directly + toggles choose which files ship

export const TOGGLE_DEFS = [
  { key: 'codeReview', label: 'Require code review before merge', rule: 'No change may be merged without at least one approving review from a scoped reviewer.' },
  { key: 'requireTests', label: 'Require passing tests', rule: 'CI tests must pass before a change is eligible for deployment.' },
  { key: 'linting', label: 'Enforce linting / formatting', rule: 'Code must pass the project linter and formatter (e.g. ESLint + Prettier) with zero errors.' },
  { key: 'piiCompliance', label: 'PII handling compliance', rule: 'Personal data must be classified, minimised, and never logged. Use the approved vault for secrets.' },
  { key: 'secretsScan', label: 'Secret scanning on commit', rule: 'Commits are scanned for leaked credentials; flagged secrets block the push.' },
  { key: 'prApproval', label: 'PR approval gate', rule: 'Pull requests require explicit approval and a linked ticket before they can be merged.' },
  { key: 'iacReview', label: 'Infra-as-code review', rule: 'Server and deployment changes must go through version-controlled IaC and be reviewed like code.' },
  { key: 'auditLog', label: 'Audit every server action', rule: 'All server access and deployment actions are recorded in the IRYS audit log.' }
];

function enabledRules(toggles) {
  return TOGGLE_DEFS.filter((t) => toggles && toggles[t.key]).map((t) => `- **${t.label}** — ${t.rule}`);
}

function bullet(list) {
  return (list && list.length ? list : []).map((x) => `- ${x}`).join('\n');
}

// ---- DESCRIBE MODE -------------------------------------------------------
function describeToFiles(cfg, project) {
  const rules = enabledRules(cfg.toggles);
  const compliance = bullet(cfg.complianceChecklist);
  const quality = bullet(cfg.qualityControls);
  const desc = (cfg.description || '').trim();

  const irysMd = `# IRYS Governance Manifest — ${project.name}

> Generated by IRYS from the provider's governance configuration.
> Scope: **${project.name}** (${project.id})
> Mode: describe · Generated ${new Date().toISOString()}

## Provider summary
${desc || '_No plain-language description was provided._'}

## Active controls
${rules.join('\n') || '_No toggles enabled._'}

## Compliance checklist
${compliance || '_No compliance checklist items._'}

## Quality controls
${quality || '_No quality controls defined._'}

## Server & deployment scope
- Servers are assigned per-project through the IRYS dashboard.
- SSH keys are provisioned by IRYS only for users in scope.
- Deployments follow the IRYS deployment procedure for this project.
`;

  const agentsMd = `# AGENTS.md — ${project.name}

You are an AI agent operating inside the **${project.name}** project, governed by IRYS.

## How this project works
${desc || 'Follow the standard IRYS operating rules below.'}

## Operating rules (enforced by IRYS)
${rules.join('\n') || '- Operate conservatively and ask before any destructive or external action.'}

## Compliance obligations
${compliance || '- Respect the provider\'s data-handling policy at all times.'}

## Quality bar
${quality || '- Keep changes small, tested, and reviewed.'}

## Server access
- You may only act on servers IRYS has placed in scope for this project.
- Never modify \`authorized_keys\` except through IRYS.
- Record non-trivial actions in the IRYS audit log.
`;

  const commandcodeMd = `# COMMANDCODE.md — ${project.name}

Command & tool-usage policy for AI agents in **${project.name}** (IRYS-governed).

## Allowed operations
- Read repository files and run the project's test/lint suite.
- Build and run the app in isolated/local environments.

## Gated operations (require IRYS scope + approval)
- SSH to project servers (key provisioned by IRYS only).
- Run deployment / systemd commands (see deployment procedure).
- Push to protected branches or publish releases.

## Forbidden
- Disabling security tooling (lint, secret scan, review gates).
- Writing to \`~/.ssh/authorized_keys\` directly.
- Exfiltrating code, credentials, or user data.
${rules.map((r) => '- ' + r.replace(/^- \*\*(.+?)\*\* — /, '$1: ')).join('\n')}
`;

  return { agentsMd, commandcodeMd, irysMd };
}

// ---- MANUAL MODE ---------------------------------------------------------
function manualToFiles(cfg, project) {
  const agentsMd = (cfg.manualSections?.agents || '').trim() ||
    `# AGENTS.md — ${project.name}\n\n(No manual content provided.)`;
  const commandcodeMd = (cfg.manualSections?.commandcode || '').trim() ||
    `# COMMANDCODE.md — ${project.name}\n\n(No manual content provided.)`;
  const irysMd = (cfg.manualSections?.irys || '').trim() ||
    `# IRYS.md — ${project.name}\n\n(No manual content provided.)`;
  return { agentsMd, commandcodeMd, irysMd };
}

export function generateGovernanceFiles(cfg, project) {
  const files = cfg.mode === 'manual' ? manualToFiles(cfg, project) : describeToFiles(cfg, project);
  return { ...files, generatedAt: new Date().toISOString() };
}
